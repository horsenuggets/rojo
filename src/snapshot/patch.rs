//! Defines the data structures used for describing instance patches.

use std::{collections::HashMap, sync::Arc};

use rbx_dom_weak::{
    types::{Ref, Variant},
    HashMapExt as _, Ustr, UstrMap,
};
use serde::{Deserialize, Serialize};

use super::{InstanceMetadata, InstanceSnapshot, InstanceWithMeta, RojoTree};

/// A set of different kinds of patches that can be applied to an WeakDom.
///
/// These patches shouldn't be persisted: there's no mechanism in place to make
/// sure that another patch wasn't applied before this one that could cause a
/// conflict!
#[derive(Debug, Default, Clone, PartialEq, Serialize, Deserialize)]
pub struct PatchSet {
    pub removed_instances: Vec<Ref>,
    pub added_instances: Vec<PatchAdd>,
    pub updated_instances: Vec<PatchUpdate>,
}

impl PatchSet {
    pub fn new() -> Self {
        PatchSet {
            removed_instances: Vec::new(),
            added_instances: Vec::new(),
            updated_instances: Vec::new(),
        }
    }
}

/// A patch containing an instance that was added to the tree.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct PatchAdd {
    pub parent_id: Ref,
    pub instance: InstanceSnapshot,
}

/// A patch indicating that properties of an instance changed.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct PatchUpdate {
    pub id: Ref,
    pub changed_name: Option<String>,
    pub changed_class_name: Option<Ustr>,
    /// The existing tree instance that becomes this instance's parent.
    #[serde(
        default,
        rename = "changedParent",
        skip_serializing_if = "Option::is_none"
    )]
    pub changed_parent: Option<Ref>,

    /// Contains all changed properties. If a property is assigned to `None`,
    /// then that property has been removed.
    pub changed_properties: UstrMap<Option<Variant>>,

    /// Changed Rojo-specific metadata, if any of it changed.
    pub changed_metadata: Option<InstanceMetadata>,
}

/// Applied patch sets have the same rough shape as PatchSet, but are
/// descriptive of the operation that happened instead of prescribing what
/// mutations to apply to the tree.
///
/// Applied patch sets are generated by applying a patch to a tree, and are
/// suitable for sending over the network to a synchronized tree like the Rojo
/// Studio plugin.
///
// TODO: Introduce machinery to detect conflicts, like keeping previous +
// current values in all fields.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum PublicationOrigin {
    Filesystem,
    Studio,
}

/// An owned instance at a Studio addition's capture boundary. This is domain data,
/// not a wire instance; transport filtering still belongs to the web interface.
#[derive(Debug, Clone)]
pub(crate) struct CapturedAdditionInstance {
    pub id: Ref,
    pub parent: Ref,
    pub name: String,
    pub class_name: Ustr,
    pub properties: UstrMap<Variant>,
    pub children: Vec<Ref>,
    pub metadata: InstanceMetadata,
}

impl CapturedAdditionInstance {
    fn capture(instance: InstanceWithMeta<'_>) -> Self {
        Self {
            id: instance.id(),
            parent: instance.parent(),
            name: instance.name().to_owned(),
            class_name: instance.class_name(),
            properties: instance.properties().clone(),
            children: instance.children().to_vec(),
            metadata: instance.metadata().clone(),
        }
    }
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct AppliedPatchSet {
    /// Assigned by the publication queue, never inferred from a client's proposal.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub origin: Option<PublicationOrigin>,
    pub removed: Vec<Ref>,
    pub added: Vec<Ref>,
    /// Studio additions cannot borrow a later tree revision. Queue history and
    /// subscriber replays share this immutable evidence without cloning subtrees.
    #[serde(skip)]
    pub(crate) captured_additions: Option<Arc<HashMap<Ref, CapturedAdditionInstance>>>,
    pub updated: Vec<AppliedPatchUpdate>,
    /// Server-only publication provenance. Never supplied by a proposed patch.
    #[serde(
        default,
        rename = "sourceOperations",
        skip_serializing_if = "std::collections::HashMap::is_empty"
    )]
    pub source_operations: std::collections::HashMap<Ref, String>,
}

impl AppliedPatchSet {
    pub fn new() -> Self {
        AppliedPatchSet {
            origin: None,
            removed: Vec::new(),
            added: Vec::new(),
            captured_additions: None,
            updated: Vec::new(),
            source_operations: Default::default(),
        }
    }

    pub fn is_empty(&self) -> bool {
        self.removed.is_empty() && self.added.is_empty() && self.updated.is_empty()
    }

    /// Freeze only Studio-origin additions, immediately after the mutation that
    /// produced them. Filesystem publications intentionally keep lazy serialization.
    pub(crate) fn capture_additions(&mut self, tree: &RojoTree) {
        if self.added.is_empty() || self.captured_additions.is_some() {
            return;
        }
        let mut captured = HashMap::new();
        let mut pending = self.added.clone();
        while let Some(id) = pending.pop() {
            // Applied patches can list both roots and descendants. Capture each
            // instance once, rather than copying every overlapping subtree.
            if captured.contains_key(&id) {
                continue;
            }
            let Some(instance) = tree.get_instance(id) else {
                continue;
            };
            pending.extend_from_slice(instance.children());
            captured.insert(id, CapturedAdditionInstance::capture(instance));
        }
        self.captured_additions = Some(Arc::new(captured));
    }

    /// Coalesce filesystem reconciliation before capturing any Studio publication.
    /// Frozen messages describe ordered capture boundaries and must stay separate.
    pub(crate) fn combine(patches: impl IntoIterator<Item = Self>) -> Self {
        use std::collections::{HashMap, HashSet};
        let mut combined = Self::new();
        let mut updates = HashMap::new();
        for patch in patches {
            assert!(
                patch.captured_additions.is_none(),
                "Combine patches before capturing Studio additions"
            );
            combined.removed.extend(patch.removed);
            combined.added.extend(patch.added);
            for update in patch.updated {
                let index = *updates.entry(update.id).or_insert_with(|| {
                    combined.updated.push(AppliedPatchUpdate::new(update.id));
                    combined.updated.len() - 1
                });
                let current = &mut combined.updated[index];
                if update.changed_name.is_some() {
                    current.changed_name = update.changed_name;
                }
                if update.changed_class_name.is_some() {
                    current.changed_class_name = update.changed_class_name;
                }
                if update.changed_parent.is_some() {
                    current.changed_parent = update.changed_parent;
                }
                if update.changed_metadata.is_some() {
                    current.changed_metadata = update.changed_metadata;
                }
                current.changed_properties.extend(update.changed_properties);
            }
        }
        let added: HashSet<_> = combined.added.iter().copied().collect();
        let removed: HashSet<_> = combined.removed.iter().copied().collect();
        let mut seen = HashSet::new();
        combined
            .removed
            .retain(|id| !added.contains(id) && seen.insert(*id));
        seen.clear();
        combined
            .added
            .retain(|id| !removed.contains(id) && seen.insert(*id));
        // Additions are serialized from the final tree. Their refreshed Source
        // already belongs to that addition, not a second undoable edit.
        combined
            .updated
            .retain(|update| !added.contains(&update.id) && !removed.contains(&update.id));
        combined
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AppliedPatchUpdate {
    pub id: Ref,

    // TODO: Store previous values in order to detect application conflicts
    pub changed_name: Option<String>,
    pub changed_class_name: Option<Ustr>,
    /// The existing tree instance that becomes this instance's parent.
    #[serde(
        default,
        rename = "changedParent",
        skip_serializing_if = "Option::is_none"
    )]
    pub changed_parent: Option<Ref>,
    pub changed_properties: UstrMap<Option<Variant>>,
    pub changed_metadata: Option<InstanceMetadata>,
}

impl AppliedPatchUpdate {
    pub fn new(id: Ref) -> Self {
        Self {
            id,
            changed_name: None,
            changed_class_name: None,
            changed_parent: None,
            changed_properties: UstrMap::new(),
            changed_metadata: None,
        }
    }
}

#[cfg(test)]
mod test {
    use super::*;
    use rbx_dom_weak::ustr;

    #[test]
    fn addition_capture_is_immutable_shared_and_never_serialized_or_deserialized() {
        let mut tree = RojoTree::new(
            InstanceSnapshot::new()
                .name("Original")
                .property("Source", "return 1")
                .children(vec![InstanceSnapshot::new().name("Child")]),
        );
        let root = tree.get_root_id();
        let mut patch = AppliedPatchSet {
            added: vec![root, tree.root().children()[0], root],
            ..AppliedPatchSet::new()
        };
        patch.capture_additions(&tree);
        let cloned = patch.clone();
        assert!(Arc::ptr_eq(
            patch.captured_additions.as_ref().unwrap(),
            cloned.captured_additions.as_ref().unwrap()
        ));
        tree.get_instance_mut(root).unwrap().inner_mut().name = "Later".into();
        patch.capture_additions(&tree);
        let captured = patch.captured_additions.as_ref().unwrap();
        assert_eq!(captured[&root].name, "Original");
        assert_eq!(captured.len(), 2);
        assert!(Arc::ptr_eq(
            patch.captured_additions.as_ref().unwrap(),
            cloned.captured_additions.as_ref().unwrap()
        ));

        let mut json = serde_json::to_value(&patch).unwrap();
        assert!(json.get("captured_additions").is_none());
        json["captured_additions"] = serde_json::json!({root.to_string(): "untrusted"});
        let decoded: AppliedPatchSet = serde_json::from_value(json).unwrap();
        assert!(decoded.captured_additions.is_none());
        let bytes = rmp_serde::to_vec_named(&patch).unwrap();
        let decoded: AppliedPatchSet = rmp_serde::from_slice(&bytes).unwrap();
        assert!(decoded.captured_additions.is_none());
    }

    #[test]
    #[should_panic(expected = "Combine patches before capturing Studio additions")]
    fn combining_captured_publications_cannot_discard_their_capture_boundary() {
        let tree = RojoTree::new(InstanceSnapshot::new());
        let mut patch = AppliedPatchSet {
            added: vec![tree.get_root_id()],
            ..AppliedPatchSet::new()
        };
        patch.capture_additions(&tree);
        AppliedPatchSet::combine([patch]);
    }

    #[test]
    fn combined_patches_replace_stale_sources_in_one_structural_edit() {
        let id = Ref::new();
        let parent = Ref::new();
        let first = AppliedPatchSet {
            updated: vec![AppliedPatchUpdate {
                changed_name: Some("RenamedShared".into()),
                changed_parent: Some(parent),
                changed_properties: [(ustr("Source"), Some(Variant::String("old path".into())))]
                    .into_iter()
                    .collect(),
                ..AppliedPatchUpdate::new(id)
            }],
            ..AppliedPatchSet::new()
        };
        let refresh = AppliedPatchSet {
            updated: vec![AppliedPatchUpdate {
                changed_properties: [(ustr("Source"), Some(Variant::String("new path".into())))]
                    .into_iter()
                    .collect(),
                ..AppliedPatchUpdate::new(id)
            }],
            ..AppliedPatchSet::new()
        };
        let combined = AppliedPatchSet::combine([first, refresh]);
        assert_eq!(combined.updated.len(), 1);
        let update = &combined.updated[0];
        assert_eq!(update.changed_name.as_deref(), Some("RenamedShared"));
        assert_eq!(update.changed_parent, Some(parent));
        assert_eq!(
            update.changed_properties[&ustr("Source")],
            Some(Variant::String("new path".into()))
        );
    }

    #[test]
    fn combined_patches_fold_updates_into_additions_and_cancel_removed_additions() {
        for removed in [false, true] {
            let id = Ref::new();
            let combined = AppliedPatchSet::combine([
                AppliedPatchSet {
                    added: vec![id],
                    ..AppliedPatchSet::new()
                },
                AppliedPatchSet {
                    removed: if removed { vec![id] } else { Vec::new() },
                    updated: vec![AppliedPatchUpdate::new(id)],
                    ..AppliedPatchSet::new()
                },
            ]);
            assert!(combined.updated.is_empty());
            assert!(combined.removed.is_empty());
            assert_eq!(combined.added, if removed { Vec::new() } else { vec![id] });
            assert_eq!(combined.is_empty(), removed);
        }
    }
}
