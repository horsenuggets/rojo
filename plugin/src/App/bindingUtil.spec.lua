return function()
	const Rojo = script:FindFirstAncestor("Rojo")
	const Roact = require(Rojo.Packages.Roact)
	const bindingUtil = require(script.Parent.bindingUtil)

	it("should map numeric endpoints through binding updates", function()
		const binding, update = Roact.createBinding(0)
		const mapped = bindingUtil.mapLerp(binding, 2, 10)

		expect(mapped:getValue()).to.equal(2)
		update(1)
		expect(mapped:getValue()).to.equal(10)
		update(0)
		expect(mapped:getValue()).to.equal(2)
	end)

	it("should interpolate intermediate numeric binding values", function()
		const binding, update = Roact.createBinding(0.25)
		const mapped = bindingUtil.mapLerp(binding, 2, 10)

		expect(mapped:getValue()).to.equal(4)
		update(0.5)
		expect(mapped:getValue()).to.equal(6)
		update(0.75)
		expect(mapped:getValue()).to.equal(8)
	end)

	it("should interpolate decreasing numeric binding values", function()
		const binding, update = Roact.createBinding(0)
		const mapped = bindingUtil.mapLerp(binding, 10, -6)

		expect(mapped:getValue()).to.equal(10)
		update(0.25)
		expect(mapped:getValue()).to.equal(6)
		update(0.5)
		expect(mapped:getValue()).to.equal(2)
		update(1)
		expect(mapped:getValue()).to.equal(-6)
	end)

	it("should interpolate Vector2 binding values", function()
		const binding, update = Roact.createBinding(0)
		const start = Vector2.new(2, 10)
		const finish = Vector2.new(10, -6)
		const mapped = bindingUtil.mapLerp(binding, start, finish)

		expect(mapped:getValue()).to.equal(start)
		update(0.25)
		expect(mapped:getValue()).to.equal(Vector2.new(4, 6))
		update(1)
		expect(mapped:getValue()).to.equal(finish)
	end)

	it("should interpolate Vector3 binding values", function()
		const binding, update = Roact.createBinding(0)
		const start = Vector3.new(2, 10, -4)
		const finish = Vector3.new(10, -6, 12)
		const mapped = bindingUtil.mapLerp(binding, start, finish)

		expect(mapped:getValue()).to.equal(start)
		update(0.5)
		expect(mapped:getValue()).to.equal(Vector3.new(6, 2, 4))
		update(1)
		expect(mapped:getValue()).to.equal(finish)
	end)
end
